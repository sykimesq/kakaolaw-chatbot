"""법률 판단 발화 차단 — 코드 레벨 안전망.

⚠️ 프롬프트만 믿으면 안 된다. 실제로 추론 모델이 시스템 프롬프트를 무시하고
   "상간소송은 …를 청구하는 사안인데, 몰랐다는 점이 중요한 쟁점이 될 수 있어요"
   같은 법률 자문을 생성한 사례가 있다(2026-08-16).

변호사법 위반 소지가 있는 발화는 사용자에게 절대 전달하지 않고,
안전한 고정 문구로 교체한다. 오탐(過차단)이 미탐보다 안전하다.
"""

import logging
import re

logger = logging.getLogger(__name__)

# 법률 판단/자문으로 간주하는 표현 패턴.
# 사실 질문("소장을 받으셨나요?")은 걸리지 않고,
# 판단·평가·조언·설명("~할 수 있습니다", "쟁점입니다")만 걸리도록 구성.
FORBIDDEN_PATTERNS: list[str] = [
    # 제도/용어 설명 ("~란", "~는 …하는 사안/제도/절차입니다")
    r"(이란|라는 것은|란)\s*[,.]?\s*\S+.{0,40}(입니다|이에요|예요)",
    # ⚠️ "가정·이혼 소송이라고 보는데 맞나요?"(분야 확인)는 차단하면 안 되므로,
    #    제도의 정의를 서술하는 형태(~란/~이란 + 설명)만 잡는다.
    r"(사안|제도|절차)(이|가)?\s*(란|이란)",
    r"(을|를)\s*(청구|주장)할\s*수\s*있",
    # 승패/책임/가능성 예측
    r"(승소|패소|인정될|기각될|받아들여질|무죄|유죄)",
    r"(가능성|여지)(이|가)?\s*(높|낮|있|없)",
    r"(책임|과실|잘못)(이|은|을)?\s*(있|없|인정|면)",
    r"(유리|불리)(하|한|할|합니다|해요)",
    # 쟁점/법적 평가
    r"(쟁점|법적으로|법률적으로|법리|요건|성립)",
    r"(위법|불법|합법|정당|부당)(입니다|이에요|해요|하다|한|합니다)",
    # 법령/판례/기준/금액
    r"(민법|형법|제\s*\d+\s*조|판례|대법원|법원의?\s*기준)",
    r"(위자료|손해배상금|합의금).{0,10}(보통|일반적으로|대략|평균|정도는|얼마)",
    r"(소멸시효|공소시효|제소기간)",
    # 조치 조언
    r"(제출|준비|보관|수집|신청|고소|대응)(하셔야|해야)\s*(합니다|해요|됩니다)",
    r"(하시는\s*게|하시길|하시기를)\s*(좋|권|추천)",
    r"(반드시|꼭)\s*\S{0,10}(하셔야|해야)",
]

_COMPILED = [re.compile(p) for p in FORBIDDEN_PATTERNS]

# 차단 시 대체 문구 — 판단은 하지 않고 사실 수집으로 되돌린다.
SAFE_REPLACEMENT = (
    "그 부분은 변호사님이 직접 확인하고 말씀드려야 하는 내용이라 "
    "제가 답변드리기 어려워요. 대신 정확히 전달드릴 수 있게, "
    "현재 어떤 상황인지 조금만 더 알려주시겠어요?"
)


def find_violation(text: str) -> str | None:
    """법률 판단 발화 패턴을 찾으면 해당 패턴 문자열을 반환, 없으면 None."""
    if not text:
        return None
    for pattern in _COMPILED:
        if pattern.search(text):
            return pattern.pattern
    return None


def sanitize(text: str) -> str:
    """법률 판단이 섞인 응답을 안전한 문구로 교체한다.

    프롬프트 위반을 최후에 막는 안전망. 차단 시 로그를 남겨 프롬프트를
    개선할 수 있게 한다.
    """
    violation = find_violation(text)
    if violation is None:
        return text
    logger.warning(
        "법률 판단 발화 차단 (pattern=%s): %s", violation, text[:120]
    )
    return SAFE_REPLACEMENT
